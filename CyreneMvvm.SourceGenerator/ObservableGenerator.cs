        sb.AppendLine("                {");
        sb.AppendLine("                    if (field != null) field.UnregisterParent(this);");
        sb.AppendLine("                    field = value;");
        sb.AppendLine($"                    {(nullable ? "if (field != null) " : "")}field.RegisterParent(this, _On{propName}Changed);");
